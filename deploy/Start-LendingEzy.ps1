function Require-Cmd([string]$name) {
  if (-not (Get-Command $name -ErrorAction SilentlyContinue)) {
    throw "Please install $name before running Lending Ezy local development."
  }
}
function Assert-Exit([string]$operation) {
  if ($LASTEXITCODE -ne 0) { throw "$operation failed (exit $LASTEXITCODE)." }
}
function Random-Hex {
  $bytes = New-Object byte[] 32
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
  return (-join ($bytes | ForEach-Object { $_.ToString('x2') }))
}
function Load-Secret([string]$key) {
  $entry = @(Get-Content -LiteralPath $secrets | Where-Object { $_.StartsWith("$key=") }) | Select-Object -First 1
  if (-not $entry) { throw "Missing $key in .env.local.test" }
  return $entry.Substring($key.Length + 1)
}
function Generated-Env([string]$path, [string]$body) {
  $marker = '# Generated by Lending Ezy local test runner'
  if (Test-Path -LiteralPath $path) {
    $first = Get-Content -LiteralPath $path -TotalCount 1
    if ($first -ne $marker) { throw "Won't overwrite existing settings: $path" }
  }
  [System.IO.File]::WriteAllText($path, ($marker + [Environment]::NewLine + $body), (New-Object System.Text.UTF8Encoding($false)))
}
function Wait-For([string]$url) {
  for ($i=0; $i -lt 60; $i++) {
    try {
      $res = Invoke-WebRequest -Uri $url -UseBasicParsing -TimeoutSec 4
      if ($res.StatusCode -ge 200 -and $res.StatusCode -lt 400) { return }
    } catch {}
    Start-Sleep -Seconds 2
  }
  throw "Service unavailable at $url. Review the log files in .local/logs."
}
